# The modulo operator is not just useful in technical interviews, though. 
# It is also useful when you are building real-world applications. 
# For # example, say you have a text file that is 50,000 lines long, and you can fit 49 lines on a page.
# How much text will there be on the last page? 
# The last page will have 20 lines because 50,000 % 49 = 20.